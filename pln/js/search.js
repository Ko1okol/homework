  // Функция для обновления отображаемого описания
  function updateDescription(tagKey) {
    const description =
      descriptions[tagKey] || "Описание для этой категории пока не добавлено.";
    descriptionDisplay.innerHTML = `<p>${description}</p>`; // Вставляем описание в <p> тег
  }

  // Добавляем обработчик клика на каждую кнопку
  buttons.forEach((button) => {
    button.addEventListener("click", function () {
      // Получаем значение data-tag из нажатой кнопки
      const tag = this.dataset.tag;

      // Обновляем описание
      if (tag) {
        // Проверяем, что data-tag существует
        updateDescription(tag);
      }

      // Управление классом 'active' для выделения кнопки
      buttons.forEach((btn) => btn.classList.remove("active")); // Снимаем активность со всех
      this.classList.add("active"); // Делаем активной нажатую
    });
  });

